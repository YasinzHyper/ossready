import { CHECK_IDS } from "../checks.js";
import { editDistance } from "../cliErrors.js";
import { COMMANDS, type CommandSpec, type OptionSpec } from "../cliSpec.js";
import { LICENSES } from "../prompts.js";
import { PACKAGE_MANAGERS } from "../templates/types.js";

/**
 * `ossready completion [shell]`: print a bash, zsh or fish completion script.
 *
 * The scripts are generated from src/cliSpec.ts (the same list `--help` and
 * docs/commands.md come from) and the doctor check catalogue, so a new
 * command, option or check id is completed without editing this file.
 */

export const SHELLS = ["bash", "zsh", "fish"] as const;
export type Shell = (typeof SHELLS)[number];

/** cac adds these to every command (`cli.help()` / `cli.version()`). */
const GLOBAL_OPTIONS: readonly OptionSpec[] = [
  { flags: "-h, --help", description: "Display help", default: false },
  {
    flags: "-v, --version",
    description: "Display version number",
    default: false,
  },
];

/** How an option's value is completed. */
export type ValueCompletion =
  | { kind: "none" }
  | { kind: "words"; words: readonly string[]; commaList?: boolean }
  | { kind: "file" };

/** One option, parsed out of its cac `flags` string. */
export interface CompletionOption {
  long: string;
  short?: string;
  description: string;
  takesValue: boolean;
  /** Repeatable options (`--check`, `--skip`) */
  repeatable: boolean;
  value: ValueCompletion;
}

export interface CompletionCommand {
  name: string;
  description: string;
  options: CompletionOption[];
  /** What the optional positional argument completes to */
  positional: "directory" | "shell" | "none";
}

function valueCompletion(long: string): ValueCompletion {
  switch (long) {
    case "--license":
      return { kind: "words", words: LICENSES };
    case "--package-manager":
      return { kind: "words", words: PACKAGE_MANAGERS };
    case "--check":
    case "--skip":
      return { kind: "words", words: CHECK_IDS, commaList: true };
    case "--config":
      return { kind: "file" };
    default:
      return { kind: "none" };
  }
}

/** Parse `-y, --yes` / `--name <name>` into its parts. */
export function parseOption(option: OptionSpec): CompletionOption {
  const long = /--[a-z][a-z-]*/.exec(option.flags)?.[0];
  if (!long) throw new Error(`Option "${option.flags}" has no long flag`);
  const short = /(?:^|[\s,])(-[a-zA-Z])(?=[\s,]|$)/.exec(option.flags)?.[1];
  const takesValue = /[<[]/.test(option.flags);
  return {
    long,
    short,
    description: option.description,
    takesValue,
    repeatable: long === "--check" || long === "--skip",
    value: takesValue ? valueCompletion(long) : { kind: "none" },
  };
}

function toCompletionCommand(spec: CommandSpec): CompletionCommand {
  return {
    name: spec.name,
    description: spec.description,
    options: [...spec.options, ...GLOBAL_OPTIONS].map(parseOption),
    positional: spec.usage.includes("[directory]")
      ? "directory"
      : spec.usage.includes("[shell]")
        ? "shell"
        : "none",
  };
}

/** Every command with its parsed options (plus `--help` / `--version`). */
export function completionModel(
  commands: readonly CommandSpec[] = COMMANDS,
): CompletionCommand[] {
  return commands.map(toCompletionCommand);
}

const HEADER = (shell: Shell) =>
  [
    `# ossready completion for ${shell}. Generated by \`ossready completion ${shell}\`;`,
    "# re-run it after upgrading ossready to pick up new commands, options and checks.",
  ].join("\n");

function flagsOf(command: CompletionCommand): string[] {
  return command.options.flatMap((o) =>
    o.short ? [o.long, o.short] : [o.long],
  );
}

// ---------------------------------------------------------------- bash

export function bashCompletion(
  commands: CompletionCommand[] = completionModel(),
): string {
  const names = commands.map((c) => c.name).join(" ");
  const valueCases: string[] = [];
  const flagCases: string[] = [];
  const positionalCases: string[] = [];
  for (const command of commands) {
    for (const option of command.options) {
      if (!option.takesValue) continue;
      const patterns = [option.long, option.short]
        .filter(Boolean)
        .map((f) => `${command.name}:${f}`)
        .join("|");
      let body: string;
      if (option.value.kind === "words") {
        const words = option.value.words.join(" ");
        body = option.value.commaList
          ? `_ossready_list "${words}"`
          : `COMPREPLY=( $(compgen -W "${words}" -- "$cur") )`;
      } else if (option.value.kind === "file") {
        body = `COMPREPLY=( $(compgen -f -- "$cur") )`;
      } else {
        body = "COMPREPLY=()";
      }
      valueCases.push(`    ${patterns}) ${body}; return ;;`);
    }
    flagCases.push(
      `    ${command.name}) flags="${flagsOf(command).join(" ")}" ;;`,
    );
    if (command.positional === "directory") {
      positionalCases.push(
        `    ${command.name}) COMPREPLY=( $(compgen -d -- "$cur") ) ;;`,
      );
    } else if (command.positional === "shell") {
      positionalCases.push(
        `    ${command.name}) COMPREPLY=( $(compgen -W "${SHELLS.join(" ")}" -- "$cur") ) ;;`,
      );
    }
  }
  return [
    HEADER("bash"),
    "# Load it with: source <(ossready completion bash)",
    "",
    "_ossready_list() {",
    "  # Complete one item of a comma-separated list (doctor --check a,b,…).",
    '  local prefix="" word="$cur"',
    '  if [[ "$cur" == *,* ]]; then prefix="${cur%,*},"; word="${cur##*,}"; fi',
    '  COMPREPLY=( $(compgen -P "$prefix" -W "$1" -- "$word") )',
    "}",
    "",
    "_ossready() {",
    "  local cur prev cmd i flags",
    '  cur="${COMP_WORDS[COMP_CWORD]}"',
    '  prev="${COMP_WORDS[COMP_CWORD-1]}"',
    '  cmd=""',
    "  for ((i = 1; i < COMP_CWORD; i++)); do",
    '    case "${COMP_WORDS[i]}" in',
    `      ${commands.map((c) => c.name).join("|")}) cmd="\${COMP_WORDS[i]}"; break ;;`,
    "    esac",
    "  done",
    '  if [[ -z "$cmd" ]]; then',
    `    COMPREPLY=( $(compgen -W "${names} --help --version -h -v" -- "$cur") )`,
    "    return",
    "  fi",
    '  case "$cmd:$prev" in',
    ...valueCases,
    "  esac",
    '  if [[ "$cur" == -* ]]; then',
    '    case "$cmd" in',
    ...flagCases,
    "    esac",
    '    COMPREPLY=( $(compgen -W "$flags" -- "$cur") )',
    "    return",
    "  fi",
    '  case "$cmd" in',
    ...positionalCases,
    "  esac",
    "}",
    "",
    "complete -o filenames -F _ossready ossready",
    "",
  ].join("\n");
}

// ---------------------------------------------------------------- zsh

/** Escape text for a zsh `_arguments` spec inside single quotes. */
function zshDescription(text: string): string {
  return text
    .replace(/\\/g, "\\\\")
    .replace(/'/g, "'\\''")
    .replace(/([[\]:])/g, "\\$1");
}

function zshOptionSpec(option: CompletionOption): string {
  const description = zshDescription(option.description);
  let action = "";
  if (option.takesValue) {
    const label = option.long.replace(/^--/, "");
    if (option.value.kind === "words") {
      action = option.value.commaList
        ? `:${label}:_values -s , ${label} ${option.value.words.join(" ")}`
        : `:${label}:(${option.value.words.join(" ")})`;
    } else if (option.value.kind === "file") {
      action = `:${label}:_files`;
    } else {
      action = `:${label}: `;
    }
  }
  const repeat = option.repeatable ? "*" : "";
  if (option.short) {
    const exclusive = option.repeatable
      ? ""
      : `(${option.short} ${option.long})`;
    return `'${exclusive}'{${repeat}${option.short},${repeat}${option.long}}'[${description}]${action}'`;
  }
  return `'${repeat}${option.long}[${description}]${action}'`;
}

export function zshCompletion(
  commands: CompletionCommand[] = completionModel(),
): string {
  const describe = commands.map(
    (c) => `    '${c.name}:${zshDescription(c.description)}'`,
  );
  const cases = commands.map((command) => {
    const specs = command.options.map((o) => `        ${zshOptionSpec(o)}`);
    if (command.positional === "directory")
      specs.push("        '1:directory:_files -/'");
    if (command.positional === "shell")
      specs.push(`        '1:shell:(${SHELLS.join(" ")})'`);
    return [
      `    ${command.name})`,
      "      _arguments \\",
      specs.join(" \\\n"),
      "      ;;",
    ].join("\n");
  });
  return [
    "#compdef ossready",
    HEADER("zsh"),
    "# Save it as _ossready in a directory on $fpath, e.g. ~/.zfunc, before compinit.",
    "",
    "_ossready() {",
    "  local context state state_descr line",
    "  typeset -A opt_args",
    "  local -a commands",
    "  commands=(",
    ...describe,
    "  )",
    "  _arguments -C \\",
    "    '(- *)'{-h,--help}'[Display help]' \\",
    "    '(- *)'{-v,--version}'[Display version number]' \\",
    "    '1: :->command' \\",
    "    '*:: :->args'",
    "  case $state in",
    "    command)",
    "      _describe -t commands 'ossready command' commands",
    "      ;;",
    "    args)",
    "      case $line[1] in",
    ...cases.map((c) => c.replace(/^/gm, "    ")),
    "      esac",
    "      ;;",
    "  esac",
    "}",
    "",
    "if [[ $zsh_eval_context[-1] == loadautofunc ]]; then",
    '  _ossready "$@"',
    "else",
    "  compdef _ossready ossready",
    "fi",
    "",
  ].join("\n");
}

// ---------------------------------------------------------------- fish

function fishQuote(text: string): string {
  return `'${text.replace(/\\/g, "\\\\").replace(/'/g, "\\'")}'`;
}

export function fishCompletion(
  commands: CompletionCommand[] = completionModel(),
): string {
  const lines: string[] = [
    HEADER("fish"),
    "# Save it as ~/.config/fish/completions/ossready.fish",
    "",
    "complete -c ossready -f",
    `complete -c ossready -n '__fish_use_subcommand' -s h -l help -d 'Display help'`,
    `complete -c ossready -n '__fish_use_subcommand' -s v -l version -d 'Display version number'`,
  ];
  for (const command of commands) {
    lines.push(
      `complete -c ossready -n '__fish_use_subcommand' -a ${command.name} -d ${fishQuote(command.description)}`,
    );
  }
  for (const command of commands) {
    const when = `-n '__fish_seen_subcommand_from ${command.name}'`;
    lines.push("");
    for (const option of command.options) {
      const parts = [`complete -c ossready ${when}`];
      if (option.short) parts.push(`-s ${option.short.slice(1)}`);
      parts.push(`-l ${option.long.slice(2)}`);
      if (option.takesValue) {
        if (option.value.kind === "words") {
          const words = option.value.commaList
            ? `'(__ossready_list ${option.value.words.join(" ")})'`
            : fishQuote(option.value.words.join(" "));
          parts.push(`-x -a ${words}`);
        } else if (option.value.kind === "file") {
          parts.push("-r -F");
        } else {
          parts.push("-x");
        }
      }
      parts.push(`-d ${fishQuote(option.description)}`);
      lines.push(parts.join(" "));
    }
    if (command.positional === "directory") {
      lines.push(
        `complete -c ossready ${when} -a '(__fish_complete_directories)'`,
      );
    } else if (command.positional === "shell") {
      lines.push(
        `complete -c ossready ${when} -a ${fishQuote(SHELLS.join(" "))}`,
      );
    }
  }
  return [
    ...lines.slice(0, 3),
    "# Complete one item of a comma-separated list (doctor --check a,b,…).",
    "function __ossready_list",
    "    set -l token (commandline -ct)",
    "    set -l prefix (string match -r '^.*,' -- $token)",
    "    for word in $argv",
    "        printf '%s%s\\n' $prefix $word",
    "    end",
    "end",
    "",
    ...lines.slice(3),
    "",
  ].join("\n");
}

// ---------------------------------------------------------------- command

/** The completion script for `shell`. */
export function completionScript(shell: Shell): string {
  switch (shell) {
    case "bash":
      return bashCompletion();
    case "zsh":
      return zshCompletion();
    case "fish":
      return fishCompletion();
  }
}

function isShell(name: string): name is Shell {
  return (SHELLS as readonly string[]).includes(name);
}

/**
 * The shell to generate for: the argument, else the basename of `$SHELL`.
 * Throws a friendly message (with a did-you-mean) for anything else.
 */
export function resolveShell(
  arg: string | undefined,
  envShell: string | undefined,
): Shell {
  if (arg !== undefined) {
    const name = arg.toLowerCase();
    if (isShell(name)) return name;
    // Only near-misses (`bsh`, `zhs`, `fsh`): `pwsh` should not suggest `bash`.
    const suggestion = SHELLS.find(
      (s) => s.startsWith(name) || editDistance(name, s) <= 1,
    );
    throw new Error(
      `Unknown shell \`${arg}\`.${suggestion ? ` Did you mean \`${suggestion}\`?` : ""} Supported shells: ${SHELLS.join(", ")}.`,
    );
  }
  const fromEnv = envShell
    ?.split(/[\\/]/)
    .pop()
    ?.replace(/\.exe$/i, "")
    .toLowerCase();
  if (fromEnv && isShell(fromEnv)) return fromEnv;
  throw new Error(
    `Could not detect your shell${fromEnv ? ` (\`$SHELL\` is ${fromEnv})` : ""}. Pass one of: ${SHELLS.join(", ")} (for example \`ossready completion bash\`).`,
  );
}

export function completionCommand(
  shell: string | undefined,
  env: NodeJS.ProcessEnv = process.env,
): void {
  const resolved = resolveShell(shell, env.SHELL);
  console.log(completionScript(resolved).trimEnd());
}
