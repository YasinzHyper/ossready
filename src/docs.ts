import { CHECK_CATALOG, type CheckInfo } from "./checks.js";
import { COMMANDS, type CommandSpec } from "./cliSpec.js";

/**
 * Markdown reference docs generated from the code: docs/checks.md from the
 * check catalogue (src/checks.ts) and docs/commands.md from the command
 * definitions (src/cliSpec.ts). `npm run docs:gen` writes them, and
 * tests/docs-up-to-date.test.ts fails when the committed files drift or the
 * output is not Prettier-clean. Pure: no file system access.
 */

/** Files `npm run docs:gen` writes, relative to the repo root. */
export const DOCS_FILES = ["docs/checks.md", "docs/commands.md"] as const;

export type DocsFile = (typeof DOCS_FILES)[number];

/** A Markdown table padded the way Prettier aligns one (cells must be ASCII). */
export function markdownTable(header: readonly string[], rows: readonly (readonly string[])[]): string[] {
  const widths = header.map((h, i) => Math.max(3, h.length, ...rows.map((row) => (row[i] ?? "").length)));
  const line = (cells: readonly string[]): string =>
    `| ${widths.map((w, i) => (cells[i] ?? "").padEnd(w)).join(" | ")} |`;
  return [line(header), line(widths.map((w) => "-".repeat(w))), ...rows.map(line)];
}

function code(text: string): string {
  return `\`${text}\``;
}

/** "a", "a and b", "a, b and c" */
function joinAnd(items: readonly string[]): string {
  if (items.length <= 1) return items.join("");
  return `${items.slice(0, -1).join(", ")} and ${items[items.length - 1]}`;
}

/** Wrap `<placeholders>` and `--flags` from CLI help text in code spans. */
export function inlineMarkdown(text: string): string {
  return text
    .replace(/<[\w-]+>(?:\/<[\w-]+>)*/g, (m) => code(m))
    .replace(/(^|[\s(])(--[a-z][a-z-]*)/g, (_m, before: string, flag: string) => `${before}${code(flag)}`);
}

function generatedNotice(source: string): string {
  return `<!-- Generated by \`npm run docs:gen\` from ${source}. Do not edit by hand. -->`;
}

/** Lines to file text: no trailing blank lines, one final newline. */
function toFile(lines: readonly string[]): string {
  return `${lines.join("\n").replace(/\n+$/, "")}\n`;
}

/** docs/checks.md: the catalogue as a table, then the details of each check. */
export function renderChecksMarkdown(checks: readonly CheckInfo[] = CHECK_CATALOG): string {
  const required = checks.filter((c) => c.level === "required").length;
  const conditional = checks.filter((c) => c.group !== undefined);
  const packageJson = conditional.filter((c) => c.group === "package-json").length;
  const others = conditional.filter((c) => c.group !== "package-json").map((c) => code(c.id));
  const lines: string[] = [
    generatedNotice("src/checks.ts"),
    "",
    "# `ossready doctor` checks",
    "",
    `\`ossready doctor\` runs ${checks.length} checks, ${required} required and ${checks.length - required} recommended. ${checks.length - conditional.length} of them always run. The other ${conditional.length} run only when they apply: ${joinAnd([`${packageJson} \`package.json\` checks for npm publish readiness`, ...others])}.`,
    "",
    "Required checks make `ossready doctor` exit with code 1 when they fail. Recommended checks are warnings that fail the run only with `--strict`. The Fix column says whether `ossready doctor --fix` can fix a failing check: yes, partial (only in some cases, see the check) or no (report only).",
    "",
    "Print this catalogue in a terminal with `ossready doctor --list`, or as JSON with `ossready doctor --list --json`. Every command and option is in [commands.md](commands.md).",
    "",
    ...markdownTable(
      ["Check", "Title", "Level", "Fix"],
      checks.map((c) => [code(c.id), c.title, c.level, c.fixable]),
    ),
    "",
    "## Details",
    "",
  ];
  for (const c of checks) {
    lines.push(
      `### ${code(c.id)}`,
      "",
      `${c.title} (${c.level}). ${c.description}`,
      "",
      `- Looks at: ${c.looksAt}`,
      `- Runs: ${c.runsWhen ?? "always"}`,
      `- Fix: ${c.fixable}. ${c.fix}`,
      "",
    );
  }
  return toFile(lines);
}

/** docs/commands.md: every command with its options and examples. */
export function renderCommandsMarkdown(commands: readonly CommandSpec[] = COMMANDS): string {
  const lines: string[] = [
    generatedNotice("src/cliSpec.ts"),
    "",
    "# `ossready` commands",
    "",
    "Every command takes an optional `[directory]` (default: the current directory). `ossready --help` and `ossready <command> --help` print the same options in a terminal, and `ossready --version` prints the installed version. The checks that `ossready doctor` runs are in [checks.md](checks.md).",
    "",
    ...commands.map(
      (c) => `- [${code(`ossready ${c.name}`)}](#ossready-${c.name}): ${inlineMarkdown(c.description)}`,
    ),
    "",
  ];
  for (const c of commands) {
    lines.push(`## ${code(`ossready ${c.name}`)}`, "", `${inlineMarkdown(c.description)}.`, "");
    if (c.note) lines.push(c.note, "");
    lines.push(`Usage: ${code(`ossready ${c.usage} [options]`)}`, "", "Options:", "");
    for (const o of c.options) lines.push(`- ${code(o.flags)}: ${inlineMarkdown(o.description)}`);
    lines.push("", "Examples:", "", "```bash", ...c.examples, "```", "");
  }
  return toFile(lines);
}

/** Every generated doc, keyed by its path relative to the repo root. */
export function renderDocs(): Record<DocsFile, string> {
  return {
    "docs/checks.md": renderChecksMarkdown(),
    "docs/commands.md": renderCommandsMarkdown(),
  };
}
